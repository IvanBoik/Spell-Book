package com.example.spellbook.data.wizard

/**
 * Языки «Книги игрока» для выбора чипами: сначала стандартные, затем экзотические.
 * Названия совпадают с каноническими из [MarkupText.languages], чтобы уже известные
 * персонажу языки можно было убрать из вариантов простым сравнением.
 */
object LanguageCatalog {

    val standard: List<String> = listOf(
        "Общий", "Дварфский", "Эльфийский", "Великаний", "Гномий", "Гоблинский", "Язык полуросликов", "Орочий",
    )

    val exotic: List<String> = listOf(
        "Язык Бездны", "Глубинная речь", "Драконий", "Инфернальный", "Небесный", "Первичный", "Сильван", "Подземный",
    )

    val all: List<String> = standard + exotic
}
