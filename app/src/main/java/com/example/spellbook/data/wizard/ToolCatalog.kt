/** Вид инструмента — по нему строятся списки «один музыкальный инструмент на ваш выбор». */
enum class ToolCategory { ARTISAN, MUSICAL, GAMING, OTHER }

/**
 * Инструмент D&D 5e.
 *
 * @param id стабильный ключ (английское название в snake_case) — хранится в выборах мастера.
 * @param name название как на dnd.su: «Инструменты кузнеца», «Лютня».
 * @param description что это за инструмент.
 * @param uses что даёт владение: какие проверки и особые применения.
 */
data class ToolInfo(
    val id: String,
    val name: String,
    val category: ToolCategory,
    val description: String,
    val uses: String,
)

