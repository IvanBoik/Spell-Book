    val all: List<ToolInfo> = ENTRIES.map { it.info }

    private val BY_ID: Map<String, ToolInfo> = all.associateBy { it.id }

    fun byId(id: String): ToolInfo? = BY_ID[id]

    /** Находит инструмент по фрагменту текста в любом падеже; при нескольких — упомянутый первым. */
    fun find(text: String): ToolInfo? = matches(normalize(text)).firstOrNull()

    /** Все инструменты, упомянутые в тексте: «набором для грима, набором для фальсификации». */
    fun findAll(text: String): List<ToolInfo> = matches(normalize(text))

    /**
     * Кандидаты для выбора по тексту правила.
     *
     * Упоминание вида («музыкальный инструмент», «игровой набор», «ремесленные инструменты»)
     * даёт все инструменты вида. Конкретные инструменты добавляются, если их предлагают
     * как альтернативу («…или…», «выберите…»), либо если вида в тексте нет вовсе.
     * Примеры в скобках «(например, …)» не учитываются, а вид, за которым следует двоеточие
     * («ремесленными инструментами на ваш выбор: …»), считается заголовком перечисления.
     * Ничего не распознано — возвращаются все инструменты.
     */
    fun candidates(ruleText: String): List<ToolInfo> {
        val text = normalize(ruleText).replace(EXAMPLES, " ")
        val categories = CATEGORY_PATTERNS.filter { (_, regex) ->
            regex.findAll(text).any { match ->
                // Вид с последующим двоеточием — заголовок списка конкретных инструментов.
                !text.substring(match.range.last + 1, minOf(text.length, match.range.last + 1 + HEADER_LOOKAHEAD))
                    .contains(':')
            }
        }.map { it.first }.toSet()
        val specific = matches(text)
        val result = when {
            categories.isEmpty() -> specific
            ALTERNATIVE.containsMatchIn(text) -> all.filter { it.category in categories } + specific
            else -> all.filter { it.category in categories }
        }.distinct()
        return result.ifEmpty { all }
    }

    // region Разбор

    private val CATEGORY_PATTERNS: List<Pair<ToolCategory, Regex>> = listOf(
        ToolCategory.ARTISAN to Regex("${W}ремесленн\\S* инструмент|${W}инструмент\\S* ремесленник"),
        ToolCategory.MUSICAL to Regex("${W}музыкальн\\S* инструмент"),
        ToolCategory.GAMING to Regex("${W}игров\\S* набор"),
    )

    /** Слова, предлагающие альтернативу: тогда конкретные инструменты — тоже варианты выбора. */
    private val ALTERNATIVE = Regex("${W}(?:или|либо|выберите)(?![а-я])")

    /** Примеры в скобках: «(например, игральные карты или ставка трёх драконов)». */
    private val EXAMPLES = Regex("\\(\\s*например[^)]*\\)")

    /** Сколько символов после названия вида проверять на двоеточие. */
    private const val HEADER_LOOKAHEAD = 25

    private fun normalize(text: String): String =
        MarkupText.plain(text).lowercase().replace('ё', 'е')

    /** Все упомянутые инструменты в порядке появления в тексте. */
    private fun matches(text: String): List<ToolInfo> =
        ENTRIES.mapNotNull { entry ->
            entry.regexes.mapNotNull { it.find(text)?.range?.first }.minOrNull()?.let { it to entry.info }
        }.sortedBy { it.first }.map { it.second }

    private fun artisan(id: String, name: String, description: String, uses: String, vararg patterns: String) =
        Entry(ToolInfo(id, name, ToolCategory.ARTISAN, description, uses), patterns.toList())

    private fun musical(id: String, name: String, description: String, vararg patterns: String) =
        Entry(ToolInfo(id, name, ToolCategory.MUSICAL, description, MUSICAL_USES), patterns.toList())

    private fun gaming(id: String, name: String, description: String, vararg patterns: String) =
        Entry(ToolInfo(id, name, ToolCategory.GAMING, description, GAMING_USES), patterns.toList())

    private fun other(id: String, name: String, description: String, uses: String, vararg patterns: String) =
        Entry(ToolInfo(id, name, ToolCategory.OTHER, description, uses), patterns.toList())

